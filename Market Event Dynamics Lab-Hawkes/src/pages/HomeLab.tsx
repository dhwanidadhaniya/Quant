import { Fragment } from "react";
import { Link } from "react-router-dom";
import { useLab } from "../state";
import { branchingMatrix, endogeneity, intensityAt, spectralRadius } from "../math/hawkes";
import { Gauge, Why, Formula } from "../components/ui";
import { CascadeCanvas, EventUniverse, IntensityRiver } from "../components/viz";
import { EVENT_SHORT } from "../math/types";

export default function HomeLab() {
  const { lab } = useLab();
  const K = branchingMatrix(lab.params);
  const rho = spectralRadius(K);
  const endo = endogeneity(lab.params);
  const tNow = lab.T * 0.72;
  const rate =
    intensityAt(tNow, lab.events, lab.params, "BUY") +
    intensityAt(tNow, lab.events, lab.params, "SELL") +
    intensityAt(tNow, lab.events, lab.params, "B_CXL") +
    intensityAt(tNow, lab.events, lab.params, "S_CXL");
  return (
    <div>
      <p className="lede">
        Intensity is the instantaneous expected rate of another event, conditional on history. This
        desk is not a blotter. It is a working argument about whether order flow is self-exciting.
      </p>
      <div className="bento">
        <div className="tile hero-tile">
          <h3>MARKET STATE · LIVE INTENSITY</h3>
          <IntensityRiver events={lab.events} params={lab.params} T={lab.T} />
          <Why>
            λ(t) is not volume and not volatility. It is the model's statement of how likely the next
            event is, right now, given everything that already printed.
          </Why>
        </div>
        <div className="tile">
          <h3>ENDOGENEITY</h3>
          <div className="big-num">{(endo * 100).toFixed(0)}</div>
          <div className="unit">% of activity attributed to cascades, not baseline μ</div>
          <Why>
            In the branching picture, total activity Λ = μ + KΛ. The leftover after immigrants is
            "the market reacting to the market." This is statistical attribution, not proof that
            traders caused each other.
          </Why>
        </div>
        <div className="tile span2">
          <h3>BRANCHING RATIO · ρ(K)</h3>
          <Gauge rho={rho} />
          <Formula>K<sub>ij</sub> = α<sub>ij</sub> / β<sub>ij</sub> · ρ(K) = spectral radius of K</Formula>
          <p style={{ color: "var(--muted)", fontSize: 14, lineHeight: 1.6 }}>
            Branching ratio measures the expected number of additional events generated by a typical
            event. A value below 1 indicates a subcritical process in which endogenous activity does
            not explode indefinitely. Near 1 the book is cascade-sensitive. At or above 1 the fitted
            exponential Hawkes is not a stationary description of this window.
          </p>
        </div>
        <div className="tile">
          <h3>ACTIVE EVENTS</h3>
          <div className="big-num">{rate.toFixed(2)}</div>
          <div className="unit">conditional events / unit time at t = 0.72 T</div>
        </div>
        <div className="tile tall">
          <h3>EXCITATION NETWORK</h3>
          <div className="matrix" style={{ marginTop: 8 }}>
            <span />
            {Object.values(EVENT_SHORT).map((h) => (
              <span className="mlab" key={h} style={{ textAlign: "center" }}>
                {h}
              </span>
            ))}
            {K.map((row, i) => (
              <Fragment key={i}>
                <span className="mlab">{Object.values(EVENT_SHORT)[i]}</span>
                {row.map((v, j) => (
                  <div
                    key={`${i}-${j}`}
                    className="mcell"
                    style={{
                      background: `rgba(255,45,149,${0.12 + 0.75 * Math.min(1, v)})`,
                      height: 36,
                      aspectRatio: "auto",
                    }}
                  >
                    {v.toFixed(2)}
                  </div>
                ))}
              </Fragment>
            ))}
          </div>
          <Link to="/matrix" className="chip" style={{ marginTop: 12 }}>
            Open matrix
          </Link>
        </div>
        <div className="tile tall span2">
          <h3>MARKET CASCADE</h3>
          <CascadeCanvas events={lab.events} />
        </div>
        <div className="tile">
          <h3>RESEARCH STATUS</h3>
          <p style={{ fontFamily: "var(--font-display)", fontSize: 28, lineHeight: 1.1 }}>
            {lab.mode === "synthetic" ? "Controlled θ* vs θ̂" : "Empirical tape"}
          </p>
          <p style={{ color: "var(--muted)", marginTop: 10, fontSize: 13, lineHeight: 1.5 }}>
            Next: calibrate, inspect residuals, then ask whether stressed regimes raise ρ(K). That is
            a question — not a slogan.
          </p>
          <div style={{ display: "flex", gap: 8, flexWrap: "wrap", marginTop: 14 }}>
            <Link className="btn" to="/calibrate">
              Calibrate
            </Link>
            <Link className="btn ghost" to="/experiments">
              Experiments
            </Link>
          </div>
        </div>
        <div className="tile span2">
          <h3>EVENT UNIVERSE · PREVIEW</h3>
          <EventUniverse events={lab.events} />
        </div>
      </div>
    </div>
  );
}
