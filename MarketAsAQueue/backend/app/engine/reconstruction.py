"""Order-book reconstruction from Level-2 events.

Given a stream of simulated (or, later, historical) add/cancel/execute
messages, rebuild price levels and FIFO queues. This is the same logic
used on real market-data feeds: the visible book is a reconstruction,
not a primitive.

Educational note
    SIMULATED DATA is generated by the engine. This module does not
    pretend to ingest a live exchange feed. The reconstruction path is
    designed so a future L2 connector can emit the same event schema.
"""

from __future__ import annotations

from app.engine.orderbook import OrderBook
from app.models.entities import Order
from app.models.types import OrderStatus, Side


def reconstruct_book(events: list[dict], tick_size: float = 0.01) -> dict:
    book = OrderBook(tick_size=tick_size)
    applied = []
    for ev in events:
        t = float(ev.get("t", 0.0))
        et = ev.get("type")
        side = Side.BID if ev.get("side") == "bid" else Side.ASK
        px = ev.get("price_ticks")
        if px is None and ev.get("price") is not None:
            px = book.ticks(float(ev["price"]))
        qty = int(ev.get("quantity") or 0)
        oid = ev.get("order_id") or f"rec-{len(applied)}"
        if et in ("limit_order", "add", "A"):
            o = Order(order_id=oid, side=side, price_ticks=int(px), quantity=qty, remaining=qty, timestamp=t)
            o.record(OrderStatus.QUEUED, t, "reconstructed add")
            book.add_limit(o, t)
            applied.append({"t": t, "op": "add", "oid": oid})
        elif et in ("cancellation", "cancel", "D"):
            if ev.get("order_id"):
                book.cancel_order(ev["order_id"], t)
            applied.append({"t": t, "op": "cancel", "oid": ev.get("order_id")})
        elif et in ("market_order", "execute", "E"):
            book.add_market(side, qty, t)
            applied.append({"t": t, "op": "execute", "qty": qty})
    return {
        "source": "SIMULATED",
        "n_events": len(events),
        "n_applied": len(applied),
        "book": book.snapshot(10),
        "applied": applied[-50:],
    }
